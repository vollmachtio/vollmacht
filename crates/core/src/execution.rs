//! Portable execution checks, not reservation or dispatch authorization.
use crate::{
    AgentPublicKey, CompactRole, MandateEnvelope, SyntaxCheckedClientData, UnverifiedPayload,
    VerificationBinding, VerificationRuntime, envelope_digest, mandate_digest, operation_digest,
};
use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD as B64};
use serde_json::Value;
use std::{fmt, time::Instant};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ExecutionError {
    Context,
    Signature,
    Evidence,
    Proof,
    Expired,
}
impl fmt::Display for ExecutionError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("execution checks rejected")
    }
}
impl std::error::Error for ExecutionError {}

/// Trusted coordinator inputs, never deserialized from an agent request.
/// Revision/enabled slots are issuer, principal, credential, agent, in that order.
pub struct ExecutionTrust {
    pub issuer_kid: String,
    pub issuer_id: String,
    pub principal_id: String,
    pub credential_id: String,
    pub agent_jkt: String,
    pub audience: String,
    pub crypto_profile: String,
    pub policy_revision: u64,
    pub registry_revisions: [u64; 4],
    pub enabled: [bool; 4],
    pub session_id: String,
    pub approval_deadline: Instant,
}
/// A pending record generated by the executor, not inferred from proof fields.
pub struct PendingExecution {
    pub challenge: String,
    pub mandate_digest: String,
    pub operation_digest: String,
    pub envelope_digest: String,
    pub issued_at: u64,
    pub expires_at: u64,
    pub deadline: Instant,
}
/// Retained original verification inputs and its committed successful result.
/// Rechecking never advances a current registry counter or updates this record.
pub struct OriginalCredential {
    pub public_key: String,
    pub counter: u32,
    pub user_handle: String,
    pub backup_eligible: bool,
    pub backed_up: bool,
    pub expected_counter: u32,
    pub expected_backed_up: bool,
}
pub struct ExecutionTime {
    pub wall_seconds: u64,
    pub monotonic: Instant,
    pub session_id: String,
}

/// Owned immutable captured context. Its construction does not authenticate
/// storage provenance, prove freshness, claim a challenge or acquire a lease.
pub struct ExecutionContext {
    approved: MandateEnvelope,
    trust: ExecutionTrust,
    pending: PendingExecution,
    credential: OriginalCredential,
    issuer: VerificationBinding,
    agent: VerificationBinding,
}
impl ExecutionContext {
    pub fn new(
        approved: MandateEnvelope,
        trust: ExecutionTrust,
        pending: PendingExecution,
        credential: OriginalCredential,
        issuer_key: &AgentPublicKey,
        agent_key: &AgentPublicKey,
    ) -> Result<Self, ExecutionError> {
        let fields = approved.approval().fields();
        for (name, expected) in [
            ("issuer_id", &trust.issuer_id),
            ("principal_id", &trust.principal_id),
            ("credential_id", &trust.credential_id),
            ("agent_jkt", &trust.agent_jkt),
            ("audience", &trust.audience),
            ("crypto_profile", &trust.crypto_profile),
        ] {
            if fields.get(name).and_then(Value::as_str) != Some(expected.as_str()) {
                return Err(ExecutionError::Context);
            }
        }
        if trust.crypto_profile != "vollmacht-local-es256-v1"
            || fields.get("policy_revision").and_then(Value::as_u64) != Some(trust.policy_revision)
            || trust
                .registry_revisions
                .iter()
                .any(|v| *v == 0 || *v > 9_007_199_254_740_991)
            || trust.enabled.contains(&false)
            || trust.session_id.len() != 32
            || !trust
                .session_id
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        {
            return Err(ExecutionError::Context);
        }
        let issued = fields
            .get("issued_at")
            .and_then(Value::as_u64)
            .ok_or(ExecutionError::Context)?;
        let expires = fields
            .get("expires_at")
            .and_then(Value::as_u64)
            .ok_or(ExecutionError::Context)?;
        let ttl = pending
            .expires_at
            .checked_sub(pending.issued_at)
            .ok_or(ExecutionError::Context)?;
        if !(1..=30).contains(&ttl)
            || pending.issued_at < issued
            || pending.expires_at > expires
            || pending.deadline > trust.approval_deadline
        {
            return Err(ExecutionError::Context);
        }
        binary(&pending.challenge, 32, 32)?;
        if pending.mandate_digest
            != B64.encode(mandate_digest(approved.approval()).map_err(|_| ExecutionError::Context)?)
            || pending.operation_digest
                != B64.encode(
                    operation_digest(approved.approval()).map_err(|_| ExecutionError::Context)?,
                )
            || pending.envelope_digest
                != B64.encode(envelope_digest(&approved).map_err(|_| ExecutionError::Context)?)
        {
            return Err(ExecutionError::Context);
        }
        binary(&credential.public_key, 1, 4096)?;
        binary(&credential.user_handle, 1, 64)?;
        if (credential.counter != 0 || credential.expected_counter != 0)
            && credential.expected_counter <= credential.counter
        {
            return Err(ExecutionError::Context);
        }
        if !credential.backup_eligible && (credential.backed_up || credential.expected_backed_up) {
            return Err(ExecutionError::Context);
        }
        let user_handle = approved
            .evidence()
            .get("user_handle")
            .and_then(Value::as_str)
            .ok_or(ExecutionError::Context)?;
        if !user_handle.is_empty() && user_handle != credential.user_handle {
            return Err(ExecutionError::Context);
        }
        let issuer = VerificationBinding::new(CompactRole::Issuer, &trust.issuer_kid, issuer_key)
            .map_err(|_| ExecutionError::Context)?;
        let agent = VerificationBinding::new(CompactRole::Execution, &trust.agent_jkt, agent_key)
            .map_err(|_| ExecutionError::Context)?;
        Ok(Self {
            approved,
            trust,
            pending,
            credential,
            issuer,
            agent,
        })
    }
    pub fn approved(&self) -> &MandateEnvelope {
        &self.approved
    }
    pub fn trust(&self) -> &ExecutionTrust {
        &self.trust
    }
    pub fn pending(&self) -> &PendingExecution {
        &self.pending
    }
    pub fn credential(&self) -> &OriginalCredential {
        &self.credential
    }
}

/// Fixed-context request to a coordinator-selected trusted verifier adapter.
pub struct EvidenceRecheckRequest<'a> {
    context: &'a ExecutionContext,
    envelope: &'a MandateEnvelope,
}
impl EvidenceRecheckRequest<'_> {
    /// Cap the helper's own budget to this original trusted attempt deadline.
    pub fn deadline(&self) -> Instant {
        self.context.pending.deadline
    }
    pub fn envelope(&self) -> &MandateEnvelope {
        self.envelope
    }
    pub fn webauthn_challenge(&self) -> &str {
        &self.context.pending.mandate_digest
    }
    pub fn credential(&self) -> &OriginalCredential {
        &self.context.credential
    }
    pub fn credential_id(&self) -> &str {
        &self.context.trust.credential_id
    }
    pub fn rp_id(&self) -> &'static str {
        "localhost"
    }
    pub fn origin(&self) -> &'static str {
        "http://localhost:8374"
    }
}
pub struct AssertionRecheckResult {
    pub new_counter: u32,
    pub backup_eligible: bool,
    pub backed_up: bool,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct EvidenceRecheckError;

/// Trusted computing boundary, selected by the coordinator, never the artifact.
/// An implementation must perform full maintained-library WebAuthn verification
/// with this exact original evidence/context and accept only correlated helper
/// success after bounded process cleanup. An incorrect implementation CAN bypass
/// cryptographic evidence checks. The type system does not establish that trust.
pub trait EvidenceRechecker {
    fn recheck(
        &self,
        request: &EvidenceRecheckRequest<'_>,
    ) -> Result<AssertionRecheckResult, EvidenceRecheckError>;
}

/// Private-field result, bound to the captured context. NOT a dispatch permit.
/// The coordinator must freshly recheck identities/status/revisions, policy,
/// session, wall/monotonic deadlines, the retained proof validity bounds and
/// remote metadata, then durably reserve. A proof can expire before its pending
/// challenge; checking only the pending expiry is insufficient.
/// Captured immutable snapshots do not prevent concurrent changes or rollbacks.
pub struct VerifiedExecutionCandidate<'a> {
    context: &'a ExecutionContext,
    proof_issued_at: u64,
    proof_expires_at: u64,
}
impl fmt::Debug for VerifiedExecutionCandidate<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("VerifiedExecutionCandidate { .. }")
    }
}
impl VerifiedExecutionCandidate<'_> {
    pub fn proof_issued_at(&self) -> u64 {
        self.proof_issued_at
    }
    pub fn proof_expires_at(&self) -> u64 {
        self.proof_expires_at
    }
    pub fn context(&self) -> &ExecutionContext {
        self.context
    }
    pub fn operation(&self) -> &Value {
        &self.context.approved.approval().fields()["operation"]
    }
}

/// Check one already-claimed matching attempt. The coordinator owns durable
/// claiming/consumption: every error after entering this function must consume
/// that attempt; success still needs reservation. This function creates no
/// challenge and cannot enforce store transactions or at-most-once dispatch.
/// `time` is a trusted captured sample, not a guarantee time cannot pass during
/// helper work. The coordinator must resample/recheck before reservation/dispatch.
pub fn verify_claimed_attempt<'a>(
    runtime: &VerificationRuntime,
    context: &'a ExecutionContext,
    issuer_bytes: &[u8],
    proof_bytes: &[u8],
    evidence: &impl EvidenceRechecker,
    time: ExecutionTime,
) -> Result<VerifiedExecutionCandidate<'a>, ExecutionError> {
    let fields = context.approved.approval().fields();
    if time.session_id != context.trust.session_id {
        return Err(ExecutionError::Context);
    }
    if time.monotonic >= context.trust.approval_deadline
        || time.monotonic >= context.pending.deadline
        || time.wall_seconds
            < fields["issued_at"]
                .as_u64()
                .ok_or(ExecutionError::Context)?
        || time.wall_seconds
            >= fields["expires_at"]
                .as_u64()
                .ok_or(ExecutionError::Context)?
        || time.wall_seconds < context.pending.issued_at
        || time.wall_seconds >= context.pending.expires_at
    {
        return Err(ExecutionError::Expired);
    }
    let signed = runtime
        .verify(issuer_bytes, &context.issuer)
        .map_err(|_| ExecutionError::Signature)?;
    let UnverifiedPayload::Issuer(envelope) = signed.artifact().payload() else {
        return Err(ExecutionError::Context);
    };
    if envelope.canonical_bytes() != context.approved.canonical_bytes() {
        return Err(ExecutionError::Context);
    }
    let client = envelope.evidence()["client_data_json"]
        .as_str()
        .ok_or(ExecutionError::Evidence)?;
    let bytes = B64.decode(client).map_err(|_| ExecutionError::Evidence)?;
    SyntaxCheckedClientData::parse(&bytes).map_err(|_| ExecutionError::Evidence)?;
    let result = evidence
        .recheck(&EvidenceRecheckRequest { context, envelope })
        .map_err(|_| ExecutionError::Evidence)?;
    if result.new_counter != context.credential.expected_counter
        || result.backup_eligible != context.credential.backup_eligible
        || result.backed_up != context.credential.expected_backed_up
        || (result.backed_up && !result.backup_eligible)
    {
        return Err(ExecutionError::Evidence);
    }
    let signed = runtime
        .verify(proof_bytes, &context.agent)
        .map_err(|_| ExecutionError::Proof)?;
    let UnverifiedPayload::Execution(proof) = signed.artifact().payload() else {
        return Err(ExecutionError::Proof);
    };
    let p = proof.fields();
    for (name, expected) in [
        ("mandate_digest", &context.pending.mandate_digest),
        ("operation_digest", &context.pending.operation_digest),
        ("envelope_digest", &context.pending.envelope_digest),
        ("challenge", &context.pending.challenge),
        ("audience", &context.trust.audience),
        ("crypto_profile", &context.trust.crypto_profile),
    ] {
        if p.get(name).and_then(Value::as_str) != Some(expected.as_str()) {
            return Err(ExecutionError::Proof);
        }
    }
    let issued = p["issued_at"].as_u64().ok_or(ExecutionError::Proof)?;
    let expires = p["expires_at"].as_u64().ok_or(ExecutionError::Proof)?;
    if issued < context.pending.issued_at || expires > context.pending.expires_at {
        return Err(ExecutionError::Proof);
    }
    if time.wall_seconds < issued || time.wall_seconds >= expires {
        return Err(ExecutionError::Expired);
    }
    Ok(VerifiedExecutionCandidate {
        context,
        proof_issued_at: issued,
        proof_expires_at: expires,
    })
}

fn binary(value: &str, min: usize, max: usize) -> Result<(), ExecutionError> {
    if value.len() > (max * 4).div_ceil(3) {
        return Err(ExecutionError::Context);
    }
    let bytes = B64.decode(value).map_err(|_| ExecutionError::Context)?;
    if !(min..=max).contains(&bytes.len()) || B64.encode(bytes) != value {
        return Err(ExecutionError::Context);
    }
    Ok(())
}
